export function CategoryIcon({ type, className = 'w-3.5 h-3.5', ...props }) {
  switch (type) {
    case 'idcard':
      return <IdCardIcon className={className} {...props} />;
    case 'receipt':
      return <ReceiptIcon className={className} {...props} />;
    case 'clipboard':
      return <ClipboardIcon className={className} {...props} />;
    case 'refresh':
      return <RefreshIcon className={className} {...props} />;
    case 'image':
      return <ImageIcon className={className} {...props} />;
    case 'document':
    default:
      return <DocumentIcon className={className} {...props} />;
  }
}
